@Suite("Data model (modeling)")
struct DataModelTests {
    /// 회원 1:N 주문 모델 (물리명까지 채운 상태)
    func shop() -> (DataModel, member: UUID, order: UUID) {
        var m = DataModel(name: "shop", kind: .mysql)
        let member = m.addTable(logicalName: "회원")
        let order = m.addTable(logicalName: "주문")
        m.tables[0].physicalName = "tb_member"
        m.tables[0].columns[0].physicalName = "id"
        m.tables[0].columns[0].logicalName = "ID"
        m.tables[0].columns.append(ModelColumn(logicalName: "이메일", physicalName: "email", dataType: "varchar(100)",
                                               notNull: true, unique: true, comment: "로그인 아이디"))
        m.tables[1].physicalName = "tb_order"
        m.tables[1].columns[0].physicalName = "order_id"
        m.tables[1].columns[0].logicalName = "주문 ID"
        m.tables[1].columns.append(ModelColumn(logicalName: "주문일시", physicalName: "ordered_at", dataType: "datetime(3)",
                                               notNull: true, defaultValue: "CURRENT_TIMESTAMP(3)"))
        return (m, member, order)
    }

    @Test func relationCopiesParentKeyAsFK() throws {
        var (m, member, order) = shop()
        let added = m.addRelation(parent: member, child: order)
        let rid = try #require(added)
        let child = try #require(m.table(order))
        let fk = try #require(child.columns.last)
        #expect(fk.physicalName == "member_id")          // id 는 흔한 이름 → 부모테이블_id
        #expect(fk.logicalName == "회원 ID")
        #expect(fk.dataType == "bigint")
        #expect(!fk.autoIncrement)
        #expect(m.relations.first?.pairs.first?.child == fk.id)

        // 삭제하면 FK 컬럼도 지운다
        m.removeRelation(rid, dropColumns: true)
        #expect(m.table(order)?.columns.contains { $0.id == fk.id } == false)
    }

    @Test func identifyingRelationJoinsPrimaryKey() throws {
        var (m, member, order) = shop()
        m.addRelation(parent: member, child: order, identifying: true)
        let pk = try #require(m.table(order)).primaryKey.map(\.physicalName)
        #expect(pk == ["order_id", "member_id"])
    }

    @Test func ddlMySQL() throws {
        var (m, member, order) = shop()
        m.addRelation(parent: member, child: order)
        let sql = try m.ddl()
        #expect(sql.contains("CREATE TABLE `tb_member` ("))
        #expect(sql.contains("`id` bigint NOT NULL auto_increment COMMENT 'ID'"))
        #expect(sql.contains("`email` varchar(100) NOT NULL COMMENT '이메일\\n로그인 아이디'")
                || sql.contains("COMMENT '이메일\n로그인 아이디'"))
        #expect(sql.contains("UNIQUE KEY `uk_tb_member_email` (`email`)"))
        #expect(sql.contains("`ordered_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)"))
        #expect(sql.contains("COMMENT='회원'"))
        #expect(sql.contains("ALTER TABLE `tb_order` ADD CONSTRAINT `fk_tb_order_tb_member` FOREIGN KEY (`member_id`) REFERENCES `tb_member` (`id`);"))
        // FK 는 CREATE 뒤에
        #expect(sql.range(of: "ALTER TABLE")!.lowerBound > sql.range(of: "CREATE TABLE `tb_order`")!.lowerBound)
    }

    @Test func ddlPostgresAndMSSQL() throws {
        var (m, member, order) = shop()
        m.addRelation(parent: member, child: order)
        let pg = try m.ddl(kind: .postgres)
        #expect(pg.contains("\"id\" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL"))
        #expect(pg.contains("COMMENT ON TABLE \"tb_member\" IS '회원';"))
        #expect(pg.contains("REFERENCES \"tb_member\" (\"id\")"))
        let ms = try m.ddl(kind: .mssql)
        #expect(ms.contains("IDENTITY(1,1)"))
        #expect(ms.contains("FOREIGN KEY ([member_id]) REFERENCES"))
    }

    @Test func missingPhysicalNameBlocksDDL() {
        var m = DataModel()
        m.addTable(logicalName: "회원")
        #expect(throws: ModelError.self) { try m.ddl() }
        #expect(m.issues().contains { $0.level == .error })
    }

    @Test func reverseEngineeringRoundTrip() throws {
        var (m, member, order) = shop()
        m.addRelation(parent: member, child: order)
        var tables = m.physicalTables()
        // DB 에서 읽은 것처럼: MySQL 기본값은 따옴표 없이
        tables[1].columns[1].defaultValue = "CURRENT_TIMESTAMP(3)"
        let r = DataModel.reverse(tables, name: "rev", kind: .mysql)
        #expect(r.tables.count == 2)
        let rm = try #require(r.tables.first { $0.physicalName == "tb_member" })
        #expect(rm.logicalName == "회원")
        let email = try #require(rm.columns.first { $0.physicalName == "email" })
        #expect(email.logicalName == "이메일")
        #expect(email.comment == "로그인 아이디")
        #expect(email.unique)
        #expect(rm.columns.first?.primaryKey == true)
        #expect(rm.columns.first?.autoIncrement == true)
        #expect(r.relations.count == 1)
        #expect(r.relations[0].parent == rm.id)
        // 다시 DDL 로 뽑아도 같은 결과
        #expect(try r.ddl() .contains("REFERENCES `tb_member` (`id`)"))
        // 모델과 DB 비교: 차이 없음
        let report = try m.compare(with: m.physicalTables())
        #expect(report.items.isEmpty)
    }

    @Test func commentSplit() {
        #expect(DataModel.commentText(logical: "회원", physical: "tb_member", comment: "") == "회원")
        #expect(DataModel.commentText(logical: "email", physical: "email", comment: "x") == "x")
        let s = DataModel.splitComment("회원\n탈퇴 회원 포함")
        #expect(s.logical == "회원")
        #expect(s.comment == "탈퇴 회원 포함")
        #expect(DataModel.reverseDefault("A", kind: .mysql) == "'A'")
        #expect(DataModel.reverseDefault("0", kind: .mysql) == "0")
    }

    @Test func storeRoundTrip() throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("goddb-model-\(UUID())")
        defer { try? FileManager.default.removeItem(at: dir) }
        let store = ModelStore(directory: dir)
        let (m, _, _) = shop()
        try store.save(m)
        let list = store.list()
        #expect(list.count == 1)
        #expect(list[0] == m || list[0].tables == m.tables)
        store.delete(m.id)
        #expect(store.list().isEmpty)
        #expect(throws: ModelError.self) { try ModelStore.decode(Data("{}".utf8)) }
    }
}

@Suite("Assistant AI context")
struct AssistantAITests {
    let member = TableMeta(name: "tb_member", comment: "회원",
                           columns: [ColumnMeta(name: "member_id", columnType: "bigint", nullable: false, columnKey: "PRI", comment: "회원 ID"),
                                     ColumnMeta(name: "email", columnType: "varchar(100)", nullable: true)],
                           indexes: [IndexMeta(name: "PRIMARY", unique: true, columns: ["member_id"])])
    var order: TableMeta {
        TableMeta(name: "tb_order", comment: "",
                  columns: [ColumnMeta(name: "order_id", columnType: "bigint", nullable: false, columnKey: "PRI"),
                            ColumnMeta(name: "member_id", columnType: "bigint", nullable: true)],
                  indexes: [IndexMeta(name: "PRIMARY", unique: true, columns: ["order_id"])],
                  foreignKeys: [ForeignKeyMeta(name: "fk_order_member", table: "tb_order", columns: ["member_id"],
                                               referencedTable: "tb_member", referencedColumns: ["member_id"])])
    }

    @Test func mentionsByPhysicalAndLogicalName() {
        let tables = [member, order]
        #expect(AssistantAI.mentionedTables("tb_order 특이사항 알려줘", in: tables).map(\.name) == ["tb_order"])
        #expect(AssistantAI.mentionedTables("회원 테이블 설명", in: tables).map(\.name) == ["tb_member"])
        // 다른 이름의 일부는 아님
        #expect(AssistantAI.mentionedTables("tb_order_item", in: tables).isEmpty)
    }

    @Test func notesFindMissingIndexAndComment() {
        let n = AssistantAI.notes(order, stats: TableStats(table: "tb_order", rows: 2_000_000, dataBytes: nil, indexBytes: nil))
        #expect(n.contains("no table comment"))
        #expect(n.contains { $0.contains("has no index") })
        #expect(n.contains { $0.contains("nullable FK") })
        #expect(n.contains { $0.contains("large table") })
    }

    @Test func contextHasNoRowsAndIncludesSQL() {
        let ctx = AssistantAI.Context(kind: .mysql, connection: "local", database: "shop", tables: [member, order],
                                      focus: [order], stats: AssistantAI.parseStats([["tb_order", "42", "16384", "0", "InnoDB", nil]]),
                                      sql: "SELECT * FROM tb_order", lastError: nil)
        let text = AssistantAI.contextText(ctx)
        #expect(text.contains("TABLE tb_order"))
        #expect(text.contains("rows≈42"))
        #expect(text.contains("SELECT * FROM tb_order"))
        #expect(text.contains("Tables referencing") == false)   // focus 는 tb_order, 참조하는 쪽 없음
        let msgs = AssistantAI.messages(kind: .mysql, context: text, history: [(role: "user", content: "q1")], english: false)
        #expect(msgs.first?.role == "system")
        #expect(msgs.last?.content == "q1")
    }

    @Test func applyPhysicalNamesFillsOnlyEmpty() {
        var m = DataModel()
        m.addTable(logicalName: "회원")
        m.tables[0].columns.append(ModelColumn(logicalName: "이메일", physicalName: "mail"))
        let answer = """
        추천이에요.
        ```json
        {"tables":[{"key":"T1","physical":"tb_member","columns":[{"key":"T1.C1","physical":"member_id"},{"key":"T1.C2","physical":"email"},{"key":"T1.C9","physical":"x"}]}]}
        ```
        """
        let n = ModelAI.applyPhysicalNames(answer, to: &m)
        #expect(n == 2)
        #expect(m.tables[0].physicalName == "tb_member")
        #expect(m.tables[0].columns[0].physicalName == "member_id")
        #expect(m.tables[0].columns[1].physicalName == "mail")   // 이미 있던 건 그대로
        #expect(ModelAI.modelText(m).contains("T1.C2 이메일 [physical: mail]"))
    }
}

@Suite struct AppGuideTests {
    static let md = """
    # GodDB 기능 명세
    ## 목차
    - 1. 모델링
    ## 15. 단축키
    | `⌘↩` | 실행 |
    ## 27. 모델링 (MySQL Workbench 모델과 비슷)
    - 상단 모드에서 모델링을 고른다. SQL 추출, 리버스 엔지니어링.
    ```
    ## not a heading
    ```
    ## 29. 접속 그룹
    - 접속 우클릭 > 그룹으로 이동
    ## 18. 변경 이력
    - 0.9.0 모델링
    """

    @Test func parseSkipsTocAndChangelog() {
        let g = AppGuide(markdown: Self.md)
        #expect(g.sections.map(\.title) == ["15. 단축키", "27. 모델링 (MySQL Workbench 모델과 비슷)", "29. 접속 그룹"])
        #expect(g.sections[1].body.contains("## not a heading"))
    }

    @Test func relevantSections() {
        let g = AppGuide(markdown: Self.md)
        #expect(g.relevant(to: "모델링에서 리버스 엔지니어링은 어떻게 해?").first?.title.hasPrefix("27.") == true)
        #expect(g.relevant(to: "접속 그룹을 어떻게 만들어?").first?.title.hasPrefix("29.") == true)
        #expect(g.relevant(to: "사용방법 알려줘").isEmpty)
        let ctx = g.contextText(question: "이거 누가 만든거야", appState: "  Mode: 쿼리")
        #expect(ctx.contains("zio0911"))
        #expect(ctx.contains("단축키"))
    }
}
