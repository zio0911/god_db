/// PostgreSQL / SQL Server 실제 서버 통합 테스트.
/// GODDB_PG_PORT, GODDB_MSSQL_PORT 환경변수가 있을 때만 실행된다. (README 의 Docker 명령 참고)
enum MultiDB {
    static let env = ProcessInfo.processInfo.environment

    static func profile(_ kind: DatabaseKind, database: String) -> (ConnectionProfile, String)? {
        switch kind {
        case .redis:
            return nil
        case .postgres:
            guard let port = env["GODDB_PG_PORT"].flatMap(Int.init) else { return nil }
            return (ConnectionProfile(kind: .postgres, name: "pg", host: "localhost", port: port,
                                      username: "postgres", database: database, useTLS: false),
                    env["GODDB_PG_PASSWORD"] ?? "goddbtest")
        case .mssql:
            guard let port = env["GODDB_MSSQL_PORT"].flatMap(Int.init) else { return nil }
            return (ConnectionProfile(kind: .mssql, name: "ms", host: "localhost", port: port,
                                      username: "sa", database: database, useTLS: false),
                    env["GODDB_MSSQL_PASSWORD"] ?? "GodDb_test1!")
        case .mysql:
            return nil
        }
    }

    /// 테스트 대상 컨테이너 (스키마/DB 이름)
    static func container(_ kind: DatabaseKind) -> String { kind == .postgres ? "public" : "shop" }

    /// 매번 같은 상태로 시작하도록 테이블을 새로 만든다.
    static func seed(_ kind: DatabaseKind) async throws -> DBSession {
        if kind == .mssql {
            let (p, pw) = profile(.mssql, database: "master")!
            let admin = try await DBSession.connect(profile: p, password: pw)
            _ = try await admin.raw("IF DB_ID('shop') IS NULL CREATE DATABASE shop")
            _ = try await admin.raw("IF DB_ID('shop_stg') IS NULL CREATE DATABASE shop_stg")
            await admin.close()
        }
        let (p, pw) = profile(kind, database: kind == .postgres ? "shop" : "shop")!
        let s = try await DBSession.connect(profile: p, password: pw)
        let sql: [String]
        switch kind {
        case .redis:
            sql = []
        case .postgres:
            sql = [
                "DROP SCHEMA IF EXISTS stg CASCADE", "CREATE SCHEMA stg",
                "DROP TABLE IF EXISTS tb_member CASCADE", "DROP TABLE IF EXISTS tb_coupon CASCADE",
                "DROP TABLE IF EXISTS tb_alter_it CASCADE",
                """
                CREATE TABLE tb_member (member_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  email varchar(100), status char(1) NOT NULL DEFAULT 'A', reg_dt timestamp NOT NULL DEFAULT now())
                """,
                "CREATE INDEX idx_email ON tb_member (email)",
                "COMMENT ON TABLE tb_member IS '회원'", "COMMENT ON COLUMN tb_member.email IS '메일'",
                "CREATE TABLE tb_coupon (id int PRIMARY KEY, code varchar(20) NOT NULL UNIQUE)",
                "INSERT INTO tb_member (email) VALUES ('kim@sample.com'), ('이@샘플.com'), (NULL)",
                "CREATE OR REPLACE VIEW v_member AS SELECT member_id, email FROM tb_member",
                "CREATE OR REPLACE FUNCTION fn_count() RETURNS bigint LANGUAGE sql AS $$ SELECT count(*) FROM tb_member $$",
                "CREATE TABLE stg.tb_member (member_id bigint PRIMARY KEY, email varchar(50), status char(1) NOT NULL DEFAULT 'A')",
            ]
        case .mssql:
            sql = [
                "USE shop",
                "IF OBJECT_ID('v_member') IS NOT NULL DROP VIEW v_member",
                "IF OBJECT_ID('sp_count') IS NOT NULL DROP PROCEDURE sp_count",
                "IF OBJECT_ID('tb_member') IS NOT NULL DROP TABLE tb_member",
                "IF OBJECT_ID('tb_coupon') IS NOT NULL DROP TABLE tb_coupon",
                "IF OBJECT_ID('tb_alter_it') IS NOT NULL DROP TABLE tb_alter_it",
                """
                CREATE TABLE tb_member (member_id bigint IDENTITY(1,1) CONSTRAINT pk_member PRIMARY KEY,
                  email nvarchar(100) NULL, status char(1) NOT NULL DEFAULT ('A'),
                  reg_dt datetime2(3) NOT NULL DEFAULT (sysdatetime()))
                """,
                "CREATE INDEX idx_email ON tb_member (email)",
                "EXEC sys.sp_addextendedproperty @name=N'MS_Description', @value=N'회원', @level0type=N'SCHEMA', @level0name=N'dbo', @level1type=N'TABLE', @level1name=N'tb_member'",
                "CREATE TABLE tb_coupon (id int CONSTRAINT pk_coupon PRIMARY KEY, code varchar(20) NOT NULL CONSTRAINT uq_coupon_code UNIQUE)",
                "INSERT INTO tb_member (email) VALUES (N'kim@sample.com'), (N'이@샘플.com'), (NULL)",
                "EXEC('CREATE VIEW v_member AS SELECT member_id, email FROM tb_member')",
                "EXEC('CREATE PROCEDURE sp_count AS SELECT COUNT(*) AS cnt FROM tb_member')",
                "USE shop_stg",
                "IF OBJECT_ID('tb_member') IS NOT NULL DROP TABLE tb_member",
                "IF OBJECT_ID('tb_coupon') IS NOT NULL DROP TABLE tb_coupon",
                "CREATE TABLE tb_member (member_id bigint CONSTRAINT pk_member_stg PRIMARY KEY, email nvarchar(50) NULL, status char(1) NOT NULL DEFAULT ('A'))",
                "USE shop",
            ]
        case .mysql:
            sql = []
        }
        for q in sql { _ = try await s.raw(q) }
        try await s.use(container(kind))
        return s
    }

    static func target(_ kind: DatabaseKind) -> String { kind == .postgres ? "stg" : "shop_stg" }
}

@Suite("PostgreSQL", .serialized, .enabled(if: MultiDB.env["GODDB_PG_PORT"] != nil))
struct PostgresIntegrationTests {
    @Test func everything() async throws { try await MultiDBChecks.run(.postgres) }
}

@Suite("SQLServer", .serialized, .enabled(if: MultiDB.env["GODDB_MSSQL_PORT"] != nil))
struct MSSQLIntegrationTests {
    @Test func everything() async throws { try await MultiDBChecks.run(.mssql) }
}

enum MultiDBChecks {
    static func run(_ kind: DatabaseKind) async throws {
        let s = try await MultiDB.seed(kind)
        let d = s.dialect
        let c = MultiDB.container(kind)

        // 연결 테스트용 서버 버전
        let version = try await s.serverVersion()
        #expect(version.hasPrefix(kind.title) && version.count > kind.title.count + 2, "\(version)")

        // DB/스키마 목록
        let dbs = try await s.databases()
        #expect(dbs.contains(c), "\(dbs)")

        // 쿼리 + 자동 LIMIT/TOP + NULL + 한글
        let r = try await s.execute("SELECT member_id, email FROM tb_member ORDER BY member_id", limit: 2)
        #expect(r.columns.map { $0.name.lowercased() } == ["member_id", "email"])
        #expect(r.rows.count == 2)
        #expect(r.rows[1].values[1] == "이@샘플.com")
        let nulls = try await s.execute("SELECT email FROM tb_member WHERE email IS NULL", limit: 500)
        #expect(nulls.rows.first?.values.first == .some(nil))

        // 페이징
        try await paging(s, table: "tb_member")
        try await serverSort(s, table: "tb_member")
        try await renameAndDrop(s, container: c)
        try await editing(s, container: c)
        try await binary(s, container: c)
        try await foreignKeys(s, container: c)

        // 날짜 형식
        let dt = try await s.execute("SELECT reg_dt FROM tb_member ORDER BY member_id", limit: 1)
        #expect(dt.rows.first?.values.first??.range(of: "^\\d{4}-\\d{2}-\\d{2} \\d{2}:\\d{2}", options: .regularExpression) != nil,
                "\(String(describing: dt.rows.first?.values.first))")

        // 스키마
        let tables = try await s.loadSchema(c)
        let member = try #require(tables.first { $0.name == "tb_member" })
        #expect(member.comment == "회원")
        #expect(member.columns.map(\.name) == ["member_id", "email", "status", "reg_dt"])
        #expect(member.columns[0].isPrimaryKey)
        #expect(member.columns[0].extra.contains("identity"))
        #expect(member.columns[2].defaultValue != nil)
        #expect(member.indexes.contains { $0.isPrimary && $0.columns == ["member_id"] })
        #expect(member.indexes.contains { $0.name == "idx_email" && !$0.isConstraint })
        let coupon = try #require(tables.first { $0.name == "tb_coupon" })
        #expect(coupon.indexes.contains { $0.unique && $0.isConstraint && !$0.isPrimary })

        // 뷰/함수/프로시저 정의
        let routines = try await s.loadRoutines(c)
        let view = try #require(routines.first { $0.kind == .view && $0.name == "v_member" })
        #expect(try await s.definition(of: view)?.lowercased().contains("member_id") == true)
        if kind == .postgres {
            let fn = try #require(routines.first { $0.kind == .function && $0.name == "fn_count" })
            #expect(try await s.definition(of: fn)?.contains("count(*)") == true)
        } else {
            let sp = try #require(routines.first { $0.kind == .procedure && $0.name == "sp_count" })
            #expect(try await s.definition(of: sp)?.contains("COUNT(*)") == true)
        }

        // 실행 계획
        let (plan, tree) = try await s.explain("SELECT * FROM tb_member WHERE status = 'A'")
        #expect(!plan.rows.isEmpty)
        #expect(tree?.isEmpty == false)
        #expect(PlanAnalyzer.warnings(plan).contains { $0.message.contains("스캔") || $0.message.contains("Scan") },
                "\(plan.rows.map(\.values))")
        // 실행 계획 뒤에도 일반 쿼리가 정상 실행돼야 한다 (SHOWPLAN OFF 확인)
        #expect(try await s.execute("SELECT COUNT(*) FROM tb_member", limit: 0).rows.first?.values.first == "3")

        // DDL 생성 → 그대로 실행 가능해야 한다
        let ddl = try await s.tableDDL(coupon)
        _ = try await s.raw(ddl.replacingOccurrences(of: d.quoteTable("tb_coupon"), with: d.quoteTable("tb_coupon_copy"))
            .replacingOccurrences(of: "pk_coupon", with: "pk_coupon_copy")
            .replacingOccurrences(of: "uq_coupon_code", with: "uq_coupon_code_copy")
            .replacingOccurrences(of: "tb_coupon_pkey", with: "tb_coupon_copy_pkey")
            .replacingOccurrences(of: "tb_coupon_code_key", with: "tb_coupon_copy_code_key"))
        _ = try await s.raw("DROP TABLE \(d.quoteTable("tb_coupon_copy"))")

        // 테이블 수정 (ALTER) → 실제 실행 후 결과 확인
        _ = try await s.raw("CREATE TABLE tb_alter_it (id int PRIMARY KEY, email varchar(100), nick varchar(20))")
        _ = try await s.raw("CREATE INDEX idx_alter_email ON tb_alter_it (email)")
        let original = try #require(try await s.loadSchema(c).first { $0.name == "tb_alter_it" })
        var cols = original.columns.map(EditableColumn.init)
        cols[1].name = "mail"
        cols[1].columnType = "varchar(200)"
        cols.remove(at: 2)
        cols.append(EditableColumn(name: "status", columnType: "char(1)", nullable: false,
                                   defaultValue: kind == .postgres ? "'A'" : "('A')", comment: "상태"))
        var idx = original.indexes.map(EditableIndex.init)
        idx = idx.map { var x = $0; if x.name == "idx_alter_email" { x.columns = ["mail"] }; return x }
        let alter = try #require(try TableAlter.statement(original: original, columns: cols, indexes: idx,
                                                          comment: "테스트", dialect: d))
        _ = try await s.raw(alter)
        let after = try #require(try await s.loadSchema(c).first { $0.name == "tb_alter_it" })
        #expect(after.columns.map(\.name) == ["id", "mail", "status"], "\(alter)")
        #expect(after.columns[1].columnType.contains("200"))
        #expect(after.columns.last?.comment == "상태")
        #expect(after.indexes.first { $0.name == "idx_alter_email" }?.columns == ["mail"])
        #expect(after.comment == "테스트")

        // 스키마 비교 → 보정 SQL 적용 → 차이 없음
        let source = try await s.loadSchema(c).filter { ["tb_member", "tb_coupon"].contains($0.name) }
        let targetName = MultiDB.target(kind)
        let target = try await s.loadSchema(targetName)
        let report = SchemaDiff.compare(source: source, target: target, dialect: d)
        #expect(report.items.contains { $0.kind == .missingTable && $0.table == "tb_coupon" })
        #expect(report.items.contains { $0.kind == .differentColumn && $0.object == "email" })
        #expect(report.items.contains { $0.kind == .missingColumn && $0.object == "reg_dt" })
        #expect(report.items.contains { $0.kind == .missingIndex && $0.object == "idx_email" })
        try await s.use(targetName)
        for item in report.items {
            guard let fix = item.fixSQL else { continue }
            do { _ = try await s.raw(fix) } catch {
                Issue.record("보정 SQL 실패: \(fix)\n\(ErrorText.describe(error).message)")
            }
        }
        let synced = try await s.loadSchema(targetName).filter { ["tb_member", "tb_coupon"].contains($0.name) }
        let again = SchemaDiff.compare(source: source, target: synced, dialect: d)
            .items.filter { $0.severity != .extra && !($0.kind == .differentColumn && $0.object == "member_id") }
        #expect(again.isEmpty, "\(again.map { "\($0.table).\($0.object ?? ""): \($0.detail)" })")
        try await s.use(c)

        // 읽기전용
        var ro = s.profile
        ro.readOnly = true
        let (_, pw) = MultiDB.profile(kind, database: "shop")!
        let rs = try await DBSession.connect(profile: ro, password: pw)
        await #expect(throws: DBError.self) { _ = try await rs.execute("DELETE FROM tb_member", limit: 0) }
        if kind == .postgres {
            await #expect(throws: (any Error).self) { _ = try await rs.raw("INSERT INTO tb_member (email) VALUES ('x')") }
        }
        await rs.close()

        // 비밀번호 오류 → 인증 실패로 인식
        var bad = s.profile
        bad.readOnly = false
        do {
            _ = try await DBSession.connect(profile: bad, password: "wrong-password")
            Issue.record("틀린 비밀번호로 연결되면 안 됨")
        } catch {
            #expect(ErrorText.isAuthFailure(error), "\(ErrorText.describe(error).message)")
        }
        await s.close()
    }
}
